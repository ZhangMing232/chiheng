/**
 * 这个文件是干什么的：
 * 盘中现价碰到计划价时，这一笔该按什么价记成交。记账脚本和网页端各有一份这样的
 * 判断，口径必须一模一样，所以抽成这一个纯函数，两边都调它。
 *
 * 你需要知道的：
 * 1. **判定和记账必须是同一个价。** 这是本文件存在的全部理由。曾经判定用现价、
 *    记账用计划价，账上最多虚记了 9.5 个百分点；而真钱硬闸 `hardGate`
 *    （「最近 20 笔均值 < −8% 就不开新仓」）读的就是这个虚高的数，
 *    于是「账面在亏」被记成「账面小亏」，闸门永远比该有的更晚触发。
 * 2. **止损和止盈的修正方向不一样，别写成同一个公式。**
 *    止损是「市价止损单」：现价已经穿到止损价下面，说明卖单成交在更差的价位，
 *    拿止损价冒充是账面做难看。往不利的方向修正，和 `journal-book.ts` 里
 *    `exitFill` 处理跳空的方向一致。
 *    但**只有现价这一个证据**——盘中拿不到开盘价，也不该拿别的东西顶替。
 *    `exitFill` 的注释里明确写过：拿收盘价顶替开盘价是不行的，因为止损触发那天
 *    收盘往往就在止损价下方，那会让每次止损都被当成跳空，系统性多算亏损。
 *    实测本项目 25 笔止损的幅度中位数只有 −2%，所以「一律按现价记」这条看似
 *    最诚实的做法恰恰会犯那个错。这是本函数只对止损做 `min()` 的原因。
 *    止盈是「限价卖单」：现价高于卖出价时，成交价就是卖出价（限价单不会成交在
 *    更差的位置），记 `target` 已经是这个方向上最保守的取值，不改。
 * 3. **跌停封死不卖，这件事不在这里判。** 调用方要先用 `limitTag` 挡掉跌停——
 *    账上根本没有 high/low，封死与否只能靠现价是否等于跌停价推测，那是另一件事。
 *    本函数只管「价格够不够触发」。
 */

/** 触发时的成交价和触发原因。 */
export type IntradayFill = {
  /** 该记进账本的卖出价 */
  price: number;
  reason: "stop" | "target";
};

/**
 * 盘中现价 `price` 碰到计划止损/止盈时，返回这一笔该记的成交价；没碰到返回 null。
 *
 * `stop > target` 这种畸形输入返回 null 而不是硬算——账本里出现过被手改坏的
 * 数据，一个说不清买卖价的输入宁可当作「没触发」，也不要记一个假成交。
 */
export function intradayFill(price: number, stop: number, target: number): IntradayFill | null {
  if (!(price > 0) || !(stop > 0) || !(target > stop)) return null;
  // 同一天两边都碰到时按止损算——止损是市价单，先成交；和 exitFill 的次序一致。
  if (price <= stop) return { price: Math.min(stop, price), reason: "stop" };
  if (price >= target) return { price: target, reason: "target" };
  return null;
}