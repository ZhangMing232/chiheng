/**
 * 这个文件是干什么的：
 * **禁止 AI 给投资动作建议** —— 学 Vibe-Research 宪法 §0 第 3 条。
 *
 * 你要做「AI 个股研判」就必须先有这一层。理由是合规，也是准确性：
 * 一个回测系统说「建议止损位 25.74」和说「按你预登记的 −25% 参数，止损位是 125.74」，
 * 前者是投资建议（要担责），后者是数据复述（只是把你自己的参数读出来）。
 *
 * ## 边界必须写清，否则会误伤自己
 *
 * ✅ **允许**：系统内部由**预登记参数**算出的数（`model.ts:planExit`、账本里的 `stop` / `target` / `hold`）。
 *    那是参数的**执行**，不是建议。
 *
 * ❌ **禁止**：AI 用**自然语言对人**说「你的止损位是 125.74」「建议加仓」「可以买入了」。
 *
 * 所以本文件管的是**自然语言输出**，不管参数通道 —— 参数通道已由 `AI-BOUNDARY.md`
 * 白名单 + `factor-expr.ts` 编译器管住，那是另一道闸。
 *
 * ## 正则为什么只拦「建议语气 + 动作词」的组合
 *
 * 「买入价 22.44」「止损价 125.74」这类**数据复述必须放行** —— 它们是策略术语，
 * 页面上天天出现。所以不能单独匹配「买入」这种词，必须要求前面有建议语气
 * （建议／推荐／可以／应该／不妨／考虑…），或后面跟动作指令（"设为止损"）。
 */

/** AI 产出只许是这四类（Vibe 宪法 §0 第 3 条）。 */
export const ALLOWED_OUTPUTS = ["数据", "分析框架", "情景概率", "裁决点"] as const;

/**
 * 禁止模式。**每条都要能说清它拦的是什么、为什么放行不了类似的说法。**
 *
 * 注意全部是「建议语气 + 动作词」或「动作指令」，不单独匹配动作词本身。
 */
export const FORBIDDEN_PATTERNS: { re: RegExp; why: string }[] = [
  {
    // 「建议加仓」「可以考虑买入」「不妨减仓」—— 建议语气 + 动作词
    re: /(建议|推荐|可以|应该|不妨|考虑|最好|不妨考虑|建议将|可将)[^。！？\n]{0,8}(建仓|加仓|减仓|清仓|补仓|买入|卖出|持有|止损|止盈|离场|进场)/,
    why: "建议语气 + 交易动作",
  },
  {
    // 「你现在该持有」「这只票可以拿」—— 对该不该持有的判断
    re: /(现在|目前|接下来)[^。！？\n]{0,6}(应该|可以|建议)[^。！？\n]{0,6}(持有|拿住|卖出|买入|观望|离场)/,
    why: "对当前持仓给出动作判断",
  },
  {
    // 「止损设在 15 元」「目标价定为 30」—— **明确的设置动作**。
    // 动作词是必需的（不是可选）：否则「止损价 20.05」这种数据复述会被误伤。
    // 这个坑是测试抓出来的——第一版把动作词写成可选，结果「买入价 22.44，止损价 20.05」
    // 整串正常数据被拦下，AI 就不敢提任何价格了。
    re: /(目标价|止盈价|止损位|止损价)[^。！？\n]{0,6}(设在|设定|放在|设为|定在|调到|下调到|上调到|改到)\s*[0-9]+/,
    why: "建议把价格锚设到某个值（含明确设置动作）",
  },
  {
    // 「你的止损位是 125.74」—— **对人称的判断句式**。
    // 关键词是「你的／这票的」这类指代 + 「是」。没有指代就是中性复述，必须放行
    // （例：「按你预登记的参数，止损位是 125.74」—— 那只是把你自己的参数读出来）。
    re: /(你的|您的|这[只支]票的?|这只的?|这个的?|该股的?|本票的?)(目标价|止盈价|止损位|止损价)(是|应在|大约在)?\s*[0-9]+/,
    why: "用「你的…是…」给出针对持仓人的价格判断",
  },
  {
    // 「如果是我，我会卖」「换作我的话」—— 用第一人称绕开
    re: /(如果是|假如是|换作|换成)(我|我的话)[^。！？\n]{0,10}(会|就)[^。！？\n]{0,6}(买|卖|持有|加|减|清|止损|离场)/,
    why: "用「如果是我」绕开建议禁令",
  },
  {
    // 「可以入手了」「该走了」—— 口语化动作指令
    re: /(可以入手|可以上车|该走|该跑|赶紧(买|卖)|快(买|卖)|是时候(买|卖))/,
    why: "口语化的买卖指令",
  },
  {
    // 「仓位可以加到五成」—— 给仓位比例
    re: /(仓位|持仓)[^。！？\n]{0,6}(加|减|降|控制|调整)[^。！？\n]{0,4}(到|至)?\s*(半仓|满仓|空仓|[一二三四五六七八九十]成|[0-9]+成|[0-9]+%)/,
    why: "给出具体仓位建议",
  },
];

export type ScreenResult = {
  /** true = 干净，可以说。false = 命中红线，不能说。 */
  ok: boolean;
  /** 命中的条目说明。给人看的，不是机器码。 */
  hits: string[];
};

/**
 * 筛一段待输出文本。
 *
 * **只管自然语言**，不碰数字通道 —— 所以「止损价 125.74」这串字符如果出现在
 * 结构化字段里（账本、参数表）不受影响，只有它出现在 AI 对用户说的话里才被拦。
 */
export function screenAdvice(text: string): ScreenResult {
  if (!text.trim()) return { ok: true, hits: [] };
  const hits: string[] = [];
  for (const p of FORBIDDEN_PATTERNS) {
    if (p.re.test(text)) hits.push(p.why);
  }
  return { ok: hits.length === 0, hits };
}

